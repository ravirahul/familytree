"""Derive public_html/install/schema-sqlite.sql from public_html/install/schema.sql (MySQL).

    python tools/make-sqlite-schema.py

Run it whenever schema.sql changes. The MySQL file is the source of truth.
"""
import re, pathlib

root = pathlib.Path(__file__).resolve().parent.parent / 'public_html' / 'install'
src = (root / 'schema.sql').read_text(encoding='utf-8')
t = src
t = re.sub(r"\s+COMMENT\s+'(?:[^']|'')*'", '', t)                 # column / table comments (may contain '')
t = re.sub(r'--.*', '', t)
t = re.sub(r'\)\s*ENGINE=\w+[^;]*;', ');', t)
t = re.sub(r'SET NAMES utf8mb4;', '', t)
t = re.sub(r'`id`\s+(?:tiny|small|big)?int(?:\(\d+\))?(?:\s+unsigned)?\s+NOT NULL\s+AUTO_INCREMENT', '`id` INTEGER PRIMARY KEY AUTOINCREMENT', t, flags=re.I)
t = re.sub(r'\s+AUTO_INCREMENT\b', '', t, flags=re.I)
# the PRIMARY KEY (`id`) line is redundant once id is INTEGER PRIMARY KEY; text ids get PRIMARY KEY inline
t = re.sub(r',?\n\s*PRIMARY KEY \(`id`\)(?=,?\n)', '', t)
t = re.sub(r"(`id`\s+(?:char|varchar)\(\d+\) NOT NULL)(?![^\n]*PRIMARY KEY)", r'\1 PRIMARY KEY', t, flags=re.I)

ALTER_KEYS = re.compile(r'ALTER TABLE `(\w+)`\n((?:\s+ADD (?:PRIMARY KEY|UNIQUE KEY|KEY)[^;]*?)+);')

def fold_keys(text):
    """Trailing ALTER TABLE ... ADD PRIMARY KEY / UNIQUE KEY / KEY blocks (phpMyAdmin style):
    primary and unique keys move into the CREATE TABLE body, plain keys become CREATE INDEX."""
    indexes = []
    for table, body in ALTER_KEYS.findall(text):
        inject = []
        for kind, name, cols in re.findall(r'ADD (PRIMARY KEY|UNIQUE KEY|KEY)\s*(`\w+`)?\s*\(([^)]*)\)', body):
            cols = re.sub(r'\(\d+\)', '', cols)
            if kind == 'PRIMARY KEY':
                if cols.strip() == '`id`':
                    continue                                   # already INTEGER PRIMARY KEY
                inject.append('PRIMARY KEY (' + cols + ')')
            elif kind == 'UNIQUE KEY':
                inject.append('UNIQUE (' + cols + ')')
            else:
                indexes.append('CREATE INDEX IF NOT EXISTS `%s_%s` ON `%s` (%s);' % (table, name.strip('`'), table, cols))
        if inject:
            pat = re.compile(r'(CREATE TABLE IF NOT EXISTS `' + table + r'` \([\s\S]*?)(\n\);)')
            text = pat.sub(lambda m: m.group(1) + ',\n  ' + ',\n  '.join(inject) + m.group(2), text, count=1)
    text = ALTER_KEYS.sub('', text)
    return text + '\n' + '\n'.join(indexes) + '\n'

t = fold_keys(t)
t = re.sub(r"\benum\s*\([^)]*\)", 'TEXT', t, flags=re.I)
t = re.sub(r'\b(long|medium|tiny)?text\b', 'TEXT', t, flags=re.I)
t = re.sub(r'\b(var)?char\(\d+\)', 'TEXT', t, flags=re.I)
t = re.sub(r'\b(tiny|small|big)?int(?:\(\d+\))?(\s+unsigned)?(?!\w)', 'INTEGER', t, flags=re.I)
t = re.sub(r'\bdecimal\([^)]*\)', 'REAL', t, flags=re.I)
t = re.sub(r'\b(datetime|timestamp|date)\b', 'TEXT', t, flags=re.I)
t = re.sub(r' ON UPDATE (current_timestamp\(\)|CURRENT_TIMESTAMP)', '', t, flags=re.I)
t = re.sub(r'DEFAULT current_timestamp\(\)', 'DEFAULT CURRENT_TIMESTAMP', t, flags=re.I)
t = re.sub(r" (CHARACTER SET|COLLATE) \w+", '', t)
t = t.replace("GENERATED ALWAYS AS (case when octet_length(`wiki`) > 100 then concat(left(`wiki`,100),'...') else `wiki` end) STORED",
              "GENERATED ALWAYS AS (CASE WHEN length(`wiki`) > 100 THEN substr(`wiki`,1,100) || '...' ELSE `wiki` END) STORED")
t = re.sub(r'\n\s*(UNIQUE )?KEY `\w+` \(([^)]*)\),?', lambda m: ('\n  UNIQUE (' + re.sub(r'\(\d+\)', '', m.group(2)) + '),') if m.group(1) else '', t)
t = re.sub(r'\n\s*CONSTRAINT[^\n]*', '', t)
t = re.sub(r',(\s*\n\s*\))', r'\1', t)
t = re.sub(r'ALTER TABLE `(\w+)`\s*\n?\s*ADD COLUMN IF NOT EXISTS `(\w+)` ([^;]*?)(\s+AFTER `\w+`)?\s*;', r'ALTER TABLE `\1` ADD COLUMN `\2` \3;', t)
t = t.replace('INSERT IGNORE', 'INSERT OR IGNORE')
t = re.sub(r'\n{3,}', '\n\n', t).strip() + '\n'
(root / 'schema-sqlite.sql').write_text('-- FamilyTree schema (SQLite). Generated by tools/make-sqlite-schema.py from schema.sql; do not edit by hand.\n' + t, encoding='utf-8', newline='\n')
print('schema-sqlite.sql:', t.count('CREATE TABLE'), 'tables,', t.count('CREATE INDEX'), 'indexes')
